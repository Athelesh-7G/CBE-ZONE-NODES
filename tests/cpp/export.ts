// Bridge, step 1: export the real graph and the TypeScript results for it.
//
//   npx tsx tests/cpp/export.ts [outDir]
//
// Writes graph.txt (nodes in NODES order, queries = all 240 ordered pairs) and
// ts_results.txt (what lib/dijkstra.ts returned for each pair). The C++ harness
// in verification/ re-checks those results with three independent solvers.
import { mkdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { dijkstra } from "../../lib/dijkstra"
import { EDGES, NODES } from "../../lib/graph"

const outDir = process.argv[2] ?? "verification/build/ts"
mkdirSync(outDir, { recursive: true })

const ids = NODES.map((n) => n.id)
const index = new Map(ids.map((id, i) => [id, i]))
const idx = (id: string): number => {
  const i = index.get(id)
  if (i === undefined) throw new Error(`unknown node id ${id}`)
  return i
}

const queries: Array<[number, number]> = []
for (let s = 0; s < ids.length; s++) {
  for (let d = 0; d < ids.length; d++) if (s !== d) queries.push([s, d])
}

const graph = [
  "# generated by tests/cpp/export.ts from lib/graph.ts; do not edit",
  ...ids.map((id, i) => `# node ${i} = ${id}`),
  "graph cbe-real",
  `${ids.length} ${EDGES.length} ${queries.length}`,
  ...EDGES.map(([a, b, w]) => `${idx(a)} ${idx(b)} ${w}`),
  ...queries.map(([s, d]) => `${s} ${d}`),
]
writeFileSync(join(outDir, "graph.txt"), graph.join("\n") + "\n")

const results = ["results cbe-real " + queries.length]
for (const [s, d] of queries) {
  const r = dijkstra(ids, EDGES, ids[s], ids[d])
  const path = r.path.map(idx)
  results.push(
    [s, d, r.found ? 1 : 0, r.found ? r.totalDistance : 0, path.length, ...path].join(" ")
  )
}
writeFileSync(join(outDir, "ts_results.txt"), results.join("\n") + "\n")

console.log(`exported ${ids.length} nodes, ${EDGES.length} edges, ${queries.length} queries to ${outDir}`)
